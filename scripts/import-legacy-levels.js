const fs = require('node:fs');
const path = require('node:path');
const { parseCampaign } = require('./campaign-parser');
const manifest = JSON.parse(fs.readFileSync('resources/levels/packs.json', 'utf8'));
if (manifest.version !== 1 || !Array.isArray(manifest.packs) || !manifest.packs.length || manifest.packs[0].id !== manifest.defaultPack) throw Error('Invalid campaign manifest/default pack');
const ids = new Set();
const packs = [];
const diagnostics = [];
for (const config of manifest.packs) {
  if (ids.has(config.id) || typeof config.file !== 'string' || path.basename(config.file) !== config.file || !config.file.endsWith('.dat')) throw Error('Invalid or duplicate pack ID/file');
  ids.add(config.id);
  const source = path.join('resources/levels', config.file);
  const result = parseCampaign(fs.readFileSync(source, 'utf8'), config, source);
  packs.push(result.pack); diagnostics.push(...result.diagnostics);
}
const output = '// Generated by npm run import:levels. Do not edit; legacy source remains unchanged.\nimport type { Pack } from "./model";\nexport const packs: Pack[] = ' + JSON.stringify(packs, null, 2) + ';\n';
const report = [
  '# Map import diagnostics',
  '',
  '[Documentation index](README.md) · [Campaign import](campaign-import.md)',
  '',
  '> [!NOTE]',
  '> Generated by `npm run import:levels`. Change the report in',
  '> [`scripts/import-legacy-levels.js`](../scripts/import-legacy-levels.js), then regenerate it.',
  '> `npm run check:levels` verifies freshness on every build.',
  '',
  '## Historical metadata policy',
  '',
  'Both canonical packs preserve 56 maps of 16×31 tiles; pack 02 is the default.',
  'Metadata applies only when its symbol matches the board cell. The stale records',
  'below are diagnosed and ignored under the canonical packs\' explicit policy.',
  'New packs should use strict metadata. Historical count lines never truncate',
  'records, and original source files remain unchanged.',
  '',
  '## Stale records',
  '',
  'Positions are zero-based **x,y** coordinates. These are preserved source-data',
  'inconsistencies, not importer failures or edits to the playable boards.',
  '',
  '| Pack | Planet | Position (zero-based) | Stale record | Actual cell |',
  '| --- | --- | --- | --- | --- |',
  ...diagnostics.map(d => `| ${d.pack} | ${d.level} | ${d.x},${d.y} | \`${d.record}\` | \`${d.actual}\` |`),
  '',
  'Source hashes and historical recovery links are in',
  '[the canonical-source notes](../resources/levels/README.md).',
  ''
].join('\n');
for (const [file, content] of [['src/main/game/packs.ts', output], ['docs/import-diagnostics.md', report]]) {
  if (process.argv.includes('--check')) {
    if (fs.readFileSync(file, 'utf8') !== content) throw Error(`${file} is stale; run npm run import:levels`);
  } else {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, content);
  }
}
console.log(`Imported ${packs.reduce((n, p) => n + p.levels.length, 0)} maps; ${diagnostics.length} stale records reported.`);
